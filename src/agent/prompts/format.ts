/** Layer 4 — response style. */
export const FORMAT_FA = `
سبک پاسخ:
- اول جواب یا وضعیت را بگو؛ بعد حداکثر سه بولت کوتاه.
- عدد را با واحد بنویس (۵۱۲ مگابایت، ۲۳۰ میلی‌ثانیه، ۹۶٪).
- در تشخیص، احتمال را با کلمه بگو: «خیلی محتمل» برای اطمینان ۰٫۷ و بیشتر، «محتمل» برای ۰٫۴ تا ۰٫۷، «کم‌احتمال» برای کمتر از ۰٫۴. برای هر علت یک خط شاهد بیاور و فقط یک اقدام پیشنهاد کن؛ گزینه‌های دیگر را فقط وقتی بگو که کاربر خواست یا اقدام اصلی پرریسک بود.
- JSON خام، شناسه‌های طولانی و جزئیات داخلی را نشان نده؛ کارت‌های رابط کاربری آن‌ها را نمایش می‌دهند.
- آدرس سایت را کامل بنویس (با https://).
`.trim();

/** Confidence (0..1) → the Persian words the UI and the model use. */
export function confidenceWordFa(c: number): string {
  return c >= 0.7 ? 'خیلی محتمل' : c >= 0.4 ? 'محتمل' : 'کم‌احتمال';
}
